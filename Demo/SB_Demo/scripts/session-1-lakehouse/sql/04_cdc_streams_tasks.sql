-- Session 1/2 — 04: CDC + event-driven pipeline with Streams and Tasks
-- xlsx: C01-AE-05 (CDC), C02-AE-04 (pipeline triggered by arrival),
--       C02-PRE-05 + C02-AE-05 (controlled failure + error visibility),
--       C02-AE-06 (rerun without duplicates), C02-AE-01 (complex SQL transforms)
-- =============================================================================
-- Flow:  STAGING.TRANSACCIONES  --stream-->  T_CDC_MERGE (MERGE, idempotent)
--          -> CORE.TRANSACCIONES_CDC (masked + RLS)
--          -> T_GOLD_RESUMEN (child task)  -> RISK_ANALYTICS.RESUMEN_DIARIO_CDC
-- Idempotent DDL (IF NOT EXISTS / CREATE OR ALTER); never CREATE OR REPLACE on
-- tables carrying policies.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 0. One-time privileges (ACCOUNTADMIN)
-- -----------------------------------------------------------------------------
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE FR_DATA_ENGINEER;
GRANT CREATE STREAM, CREATE TASK, CREATE TABLE ON SCHEMA SUPERINTENDENCY_DEMO_DB.STAGING_SCHEMA TO ROLE FR_DATA_ENGINEER;
GRANT CREATE TABLE, CREATE TASK ON SCHEMA SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA TO ROLE FR_DATA_ENGINEER;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA SUPERINTENDENCY_DEMO_DB.RISK_ANALYTICS_SCHEMA TO ROLE FR_DATA_ENGINEER;

-- -----------------------------------------------------------------------------
-- 1. Stream (CDC) on the bronze table + silver/gold targets
-- -----------------------------------------------------------------------------
USE ROLE FR_DATA_ENGINEER;
USE WAREHOUSE WH_INGESTION_MEDIUM;
USE DATABASE SUPERINTENDENCY_DEMO_DB;

CREATE STREAM IF NOT EXISTS STAGING_SCHEMA.STR_TRANSACCIONES
  ON TABLE STAGING_SCHEMA.TRANSACCIONES
  COMMENT = 'CDC of bronze transactions (C01-AE-05)';

CREATE TABLE IF NOT EXISTS CORE_BANKING_SCHEMA.TRANSACCIONES_CDC (
    ID_TRANSACCION     VARCHAR(25) NOT NULL,
    ID_TARJETA         VARCHAR(20),
    RUT                VARCHAR(20),
    FECHA_TRANSACCION  TIMESTAMP_NTZ,
    MONTO              NUMBER(14,2),
    CATEGORIA          VARCHAR(40),
    COMERCIO           VARCHAR(80),
    ESTADO             VARCHAR(20),
    UNIDAD_NEGOCIO     VARCHAR(20),
    VERSION_CDC        NUMBER DEFAULT 1,
    ACTUALIZADO_EN     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_TRANSACCIONES_CDC PRIMARY KEY (ID_TRANSACCION)
) COMMENT = 'Silver: transactions kept in sync from STAGING via stream + MERGE';

CREATE TABLE IF NOT EXISTS RISK_ANALYTICS_SCHEMA.RESUMEN_DIARIO_CDC (
    FECHA            DATE,
    UNIDAD_NEGOCIO   VARCHAR(20),
    TRANSACCIONES    NUMBER,
    RECHAZADAS       NUMBER,
    MONTO_TOTAL      NUMBER(18,2),
    CALCULADO_EN     TIMESTAMP_NTZ
) COMMENT = 'Gold: daily summary refreshed by T_GOLD_RESUMEN';

-- -----------------------------------------------------------------------------
-- 2. Governance on the new silver table (same policies as the core table)
-- -----------------------------------------------------------------------------
USE ROLE FR_DEMO_ADMIN;
ALTER TABLE SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.TRANSACCIONES_CDC
  MODIFY COLUMN RUT SET MASKING POLICY SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.MASK_NATIONAL_ID;
ALTER TABLE SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.TRANSACCIONES_CDC
  ADD ROW ACCESS POLICY SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.RLS_BUSINESS_UNIT ON (UNIDAD_NEGOCIO);
-- (if re-running: "already attached" errors on these two statements are expected)

-- -----------------------------------------------------------------------------
-- 3. Tasks: root runs only when the stream has data; child refreshes gold
-- -----------------------------------------------------------------------------
USE ROLE FR_DATA_ENGINEER;

CREATE OR ALTER TASK STAGING_SCHEMA.T_CDC_MERGE
  WAREHOUSE = WH_INGESTION_MEDIUM
  SCHEDULE = '1 MINUTE'
  COMMENT = 'C02-AE-04: fires only when new data arrives (SYSTEM$STREAM_HAS_DATA)'
  WHEN SYSTEM$STREAM_HAS_DATA('SUPERINTENDENCY_DEMO_DB.STAGING_SCHEMA.STR_TRANSACCIONES')
AS
MERGE INTO SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.TRANSACCIONES_CDC t
USING (
    -- ROW_NUMBER keeps only the latest version of each id inside the batch
    SELECT * FROM (
        SELECT s.*, ROW_NUMBER() OVER (PARTITION BY ID_TRANSACCION ORDER BY CARGADO_EN DESC) AS RN
        FROM SUPERINTENDENCY_DEMO_DB.STAGING_SCHEMA.STR_TRANSACCIONES s
        WHERE METADATA$ACTION = 'INSERT'
    ) WHERE RN = 1
) s
ON t.ID_TRANSACCION = s.ID_TRANSACCION
WHEN MATCHED AND (t.MONTO <> s.MONTO OR t.ESTADO <> s.ESTADO) THEN UPDATE SET
    MONTO = s.MONTO, ESTADO = s.ESTADO, CATEGORIA = s.CATEGORIA, COMERCIO = s.COMERCIO,
    VERSION_CDC = t.VERSION_CDC + 1, ACTUALIZADO_EN = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT
    (ID_TRANSACCION, ID_TARJETA, RUT, FECHA_TRANSACCION, MONTO, CATEGORIA, COMERCIO, ESTADO, UNIDAD_NEGOCIO)
    VALUES (s.ID_TRANSACCION, s.ID_TARJETA, s.RUT, s.FECHA_TRANSACCION, s.MONTO, s.CATEGORIA, s.COMERCIO, s.ESTADO, s.UNIDAD_NEGOCIO);

CREATE OR ALTER TASK CORE_BANKING_SCHEMA.T_GOLD_RESUMEN
  WAREHOUSE = WH_INGESTION_MEDIUM
  COMMENT = 'Child of T_CDC_MERGE: refreshes the gold summary'
  AFTER STAGING_SCHEMA.T_CDC_MERGE
AS
INSERT OVERWRITE INTO SUPERINTENDENCY_DEMO_DB.RISK_ANALYTICS_SCHEMA.RESUMEN_DIARIO_CDC
SELECT FECHA_TRANSACCION::DATE, UNIDAD_NEGOCIO, COUNT(*),
       COUNT_IF(ESTADO = 'RECHAZADA'), SUM(MONTO), CURRENT_TIMESTAMP()
FROM SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.TRANSACCIONES_CDC
GROUP BY 1, 2;

-- Children first, then root
ALTER TASK CORE_BANKING_SCHEMA.T_GOLD_RESUMEN RESUME;
ALTER TASK STAGING_SCHEMA.T_CDC_MERGE RESUME;

