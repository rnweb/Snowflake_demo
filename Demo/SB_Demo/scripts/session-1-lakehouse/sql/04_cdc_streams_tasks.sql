CREATE OR ALTER TASK STAGING_SCHEMA.T_FALLA_CONTROLADA
  WAREHOUSE = WH_INGESTION_MEDIUM
  COMMENT = 'C02-AE-05: fails on purpose (source table missing)'
AS
