-- After ~20 s: STATE = FAILED with the error message. Also visible in
-- Snowsight > Monitoring > Task History (and alertable via notification integration).
SELECT NAME, STATE, ERROR_CODE, ERROR_MESSAGE, SCHEDULED_TIME
FROM TABLE(SUPERINTENDENCY_DEMO_DB.INFORMATION_SCHEMA.TASK_HISTORY(
       TASK_NAME => 'T_FALLA_CONTROLADA',
       SCHEDULED_TIME_RANGE_START => DATEADD('hour', -1, CURRENT_TIMESTAMP())))
ORDER BY SCHEDULED_TIME DESC;

-- -----------------------------------------------------------------------------
-- 7. C02-AE-01 — complex transformations (FULL OUTER JOIN, ROW_NUMBER, DISTINCT,
--    window aggregates) as a governed view on top of the pipeline output
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW SUPERINTENDENCY_DEMO_DB.RISK_ANALYTICS_SCHEMA.VW_CONCILIACION_TARJETAS
  COMMENT = 'C02-AE-01: card reconciliation (FULL OUTER JOIN), last transaction per card (ROW_NUMBER), distinct merchants'
AS
WITH ULTIMA_TX AS (
    SELECT ID_TARJETA, FECHA_TRANSACCION, MONTO, COMERCIO,
           ROW_NUMBER() OVER (PARTITION BY ID_TARJETA ORDER BY FECHA_TRANSACCION DESC) AS RN
    FROM SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.TRANSACCIONES_CDC
),
COMERCIOS AS (
    SELECT ID_TARJETA, COUNT(DISTINCT COMERCIO) AS COMERCIOS_DISTINTOS,
           SUM(MONTO) AS MONTO_TOTAL
    FROM SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.TRANSACCIONES_CDC
    GROUP BY ID_TARJETA
)
SELECT COALESCE(c.ID_TARJETA, u.ID_TARJETA)                 AS ID_TARJETA,
       c.TIPO, c.UNIDAD_NEGOCIO, c.LIMITE_CREDITO,
       u.FECHA_TRANSACCION                                  AS ULTIMA_TRANSACCION,
       u.COMERCIO                                           AS ULTIMO_COMERCIO,
       m.COMERCIOS_DISTINTOS, m.MONTO_TOTAL,
       ROUND(DIV0(m.MONTO_TOTAL, c.LIMITE_CREDITO) * 100, 1) AS PCT_LIMITE_USADO,
       CASE WHEN c.ID_TARJETA IS NULL THEN 'TX SIN TARJETA'
            WHEN u.ID_TARJETA IS NULL THEN 'TARJETA SIN TX'
            ELSE 'OK' END                                   AS ESTADO_CONCILIACION
FROM SUPERINTENDENCY_DEMO_DB.STAGING_SCHEMA.TARJETAS_CREDITO c
FULL OUTER JOIN (SELECT * FROM ULTIMA_TX WHERE RN = 1) u ON u.ID_TARJETA = c.ID_TARJETA
LEFT JOIN COMERCIOS m ON m.ID_TARJETA = COALESCE(c.ID_TARJETA, u.ID_TARJETA);

SELECT ESTADO_CONCILIACION, COUNT(*) FROM SUPERINTENDENCY_DEMO_DB.RISK_ANALYTICS_SCHEMA.VW_CONCILIACION_TARJETAS GROUP BY 1;

