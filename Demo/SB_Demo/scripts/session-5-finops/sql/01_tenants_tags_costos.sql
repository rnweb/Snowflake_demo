-- Model
--   Tenant = department with its OWN database, warehouse, role and budget:
--     DEPTO_RIESGO  -> SB_TENANT_RIESGO_DB / WH_TENANT_RIESGO / FR_TENANT_RIESGO / RM_TENANT_RIESGO
--     DEPTO_FRAUDE  -> SB_TENANT_FRAUDE_DB / WH_TENANT_FRAUDE / FR_TENANT_FRAUDE / RM_TENANT_FRAUDE
--   Both read the governed mart through a view in their own DB, so masking and
--   RLS keep applying (each tenant role has its own ROLE_MAPPING rows).
--   Tags COST_CENTER / AMBIENTE / PROYECTO on warehouses and databases drive
--   showback/chargeback (Snowsight > Admin > Cost Management also filters by tag).
-- Idempotent. Run as ACCOUNTADMIN (resource monitors and account tags need it).
-- ACCOUNT_USAGE views lag up to ~3 h: run section 5 after some usage exists.
-- =============================================================================
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_APP_MEDIUM;

-- -----------------------------------------------------------------------------
-- 1. Tag model (C09-PRE-01)
-- -----------------------------------------------------------------------------
CREATE TAG IF NOT EXISTS SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.COST_CENTER
  ALLOWED_VALUES 'CC-100-PLATAFORMA', 'CC-200-RIESGO', 'CC-300-FRAUDE'
  COMMENT = 'Centro de costo para showback/chargeback (C09).';
CREATE TAG IF NOT EXISTS SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.AMBIENTE
  ALLOWED_VALUES 'PROD', 'DEV', 'SANDBOX'
  COMMENT = 'Ambiente del recurso (C09).';
CREATE TAG IF NOT EXISTS SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.PROYECTO
  ALLOWED_VALUES 'DEMO_SB_PLATAFORMA', 'RIESGO_CREDITICIO', 'PREVENCION_FRAUDE'
  COMMENT = 'Iniciativa/proyecto (C09).';

-- -----------------------------------------------------------------------------
-- 2. Tenants: database + warehouse + role per department (PG-17)
-- -----------------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS SB_TENANT_RIESGO_DB COMMENT = 'Tenant departamento de Riesgo (PG-17).';
CREATE DATABASE IF NOT EXISTS SB_TENANT_FRAUDE_DB COMMENT = 'Tenant departamento de Prevención de Fraude (PG-17).';
CREATE SCHEMA IF NOT EXISTS SB_TENANT_RIESGO_DB.TRABAJO;
CREATE SCHEMA IF NOT EXISTS SB_TENANT_FRAUDE_DB.TRABAJO;

CREATE WAREHOUSE IF NOT EXISTS WH_TENANT_RIESGO
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Cómputo exclusivo del tenant Riesgo.';
CREATE WAREHOUSE IF NOT EXISTS WH_TENANT_FRAUDE
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
