-- -----------------------------------------------------------------------------
-- 5. Showback / chargeback report (C09-AE-01) — feed for Power BI or Snowsight
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.VW_COSTO_POR_ETIQUETA
  COMMENT = 'C09-AE-01: créditos de cómputo por centro de costo / ambiente / proyecto (showback).'
AS
WITH TAGS AS (
    SELECT OBJECT_NAME AS WAREHOUSE_NAME,
           MAX(IFF(TAG_NAME = 'COST_CENTER', TAG_VALUE, NULL)) AS COST_CENTER,
           MAX(IFF(TAG_NAME = 'AMBIENTE',    TAG_VALUE, NULL)) AS AMBIENTE,
           MAX(IFF(TAG_NAME = 'PROYECTO',    TAG_VALUE, NULL)) AS PROYECTO
    FROM SNOWFLAKE.ACCOUNT_USAGE.TAG_REFERENCES
    WHERE DOMAIN = 'WAREHOUSE' AND TAG_DATABASE = 'SUPERINTENDENCY_DEMO_DB'
      AND TAG_SCHEMA = 'GOVERNANCE_SCHEMA' AND OBJECT_DELETED IS NULL
    GROUP BY OBJECT_NAME
)
SELECT DATE_TRUNC('day', m.START_TIME)::DATE        AS DIA,
       m.WAREHOUSE_NAME,
       COALESCE(t.COST_CENTER, 'SIN_ETIQUETA')      AS COST_CENTER,
       COALESCE(t.AMBIENTE,    'SIN_ETIQUETA')      AS AMBIENTE,
       COALESCE(t.PROYECTO,    'SIN_ETIQUETA')      AS PROYECTO,
       SUM(m.CREDITS_USED_COMPUTE)                  AS CREDITOS_COMPUTO,
       SUM(m.CREDITS_USED_CLOUD_SERVICES)           AS CREDITOS_CLOUD_SERVICES,
       SUM(m.CREDITS_USED)                          AS CREDITOS_TOTAL
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY m
LEFT JOIN TAGS t ON t.WAREHOUSE_NAME = m.WAREHOUSE_NAME
WHERE m.START_TIME >= DATEADD('day', -30, CURRENT_DATE())
GROUP BY 1, 2, 3, 4, 5;

-- Showback by cost center (last 30 days) — prints a chargeback-ready table
SELECT COST_CENTER, AMBIENTE, PROYECTO, ROUND(SUM(CREDITOS_TOTAL), 3) AS CREDITOS,
       ROUND(SUM(CREDITOS_TOTAL) * 3, 2) AS USD_ESTIMADO   -- trial list price ~USD 3/credit (Enterprise)
FROM SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.VW_COSTO_POR_ETIQUETA
GROUP BY 1, 2, 3 ORDER BY CREDITOS DESC;

