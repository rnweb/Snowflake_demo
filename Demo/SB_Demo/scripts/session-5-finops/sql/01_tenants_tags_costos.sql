       END_TIME_RANGE_START => DATEADD('hour', -2, CURRENT_TIMESTAMP()), RESULT_LIMIT => 10000))
WHERE WAREHOUSE_NAME IN ('WH_TENANT_RIESGO', 'WH_TENANT_FRAUDE')
GROUP BY 1, 2 ORDER BY 1, 2;
