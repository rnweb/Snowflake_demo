GRANT USAGE ON WAREHOUSE WH_TENANT_FRAUDE TO ROLE FR_TENANT_FRAUDE;
GRANT USAGE ON DATABASE SB_TENANT_RIESGO_DB TO ROLE FR_TENANT_RIESGO;
GRANT USAGE ON DATABASE SB_TENANT_FRAUDE_DB TO ROLE FR_TENANT_FRAUDE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SB_TENANT_RIESGO_DB.TRABAJO TO ROLE FR_TENANT_RIESGO;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SB_TENANT_FRAUDE_DB.TRABAJO TO ROLE FR_TENANT_FRAUDE;

-- Shared governed data: read access to the mart (masking + RLS still apply)
GRANT USAGE ON DATABASE SUPERINTENDENCY_DEMO_DB TO ROLE FR_TENANT_RIESGO;
GRANT USAGE ON DATABASE SUPERINTENDENCY_DEMO_DB TO ROLE FR_TENANT_FRAUDE;
GRANT USAGE ON SCHEMA SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA TO ROLE FR_TENANT_RIESGO;
GRANT USAGE ON SCHEMA SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA TO ROLE FR_TENANT_FRAUDE;
GRANT SELECT ON TABLE SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.CREDIT_CARD_TRANSACTIONS TO ROLE FR_TENANT_RIESGO;
GRANT SELECT ON TABLE SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.CREDIT_CARD_TRANSACTIONS TO ROLE FR_TENANT_FRAUDE;

-- RLS rows: Riesgo sees the 3 units, Fraude only PYME (without rows the policy returns 0 rows)
