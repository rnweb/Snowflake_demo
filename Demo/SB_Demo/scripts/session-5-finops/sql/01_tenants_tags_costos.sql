SELECT r.ROLE_NAME, r.BUSINESS_UNIT, r.DESCRIPTION
FROM (SELECT * FROM VALUES
        ('FR_TENANT_RIESGO', 'CORPORATIVO', 'Tenant Riesgo (PG-17)'),
        ('FR_TENANT_RIESGO', 'PYME',        'Tenant Riesgo (PG-17)'),
        ('FR_TENANT_RIESGO', 'RETAIL',      'Tenant Riesgo (PG-17)'),
        ('FR_TENANT_FRAUDE', 'PYME',        'Tenant Fraude (PG-17)')
      AS v(ROLE_NAME, BUSINESS_UNIT, DESCRIPTION)) r
WHERE NOT EXISTS (SELECT 1 FROM SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.ROLE_MAPPING m
                  WHERE m.ROLE_NAME = r.ROLE_NAME AND m.BUSINESS_UNIT = r.BUSINESS_UNIT);

