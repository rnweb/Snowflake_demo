USE ROLE ACCOUNTADMIN;

-- -----------------------------------------------------------------------------
-- 1. Scaling policy (C02-PRE-04): multi-cluster, auto scale-out/in, budget cap
-- -----------------------------------------------------------------------------
CREATE WAREHOUSE IF NOT EXISTS WH_CARGA_ELASTICA
  WAREHOUSE_SIZE = 'XSMALL'
  MIN_CLUSTER_COUNT = 1
  MAX_CLUSTER_COUNT = 1            -- phase "ANTES": single cluster (see section 3)
  SCALING_POLICY = 'STANDARD'      -- adds a cluster as soon as queries queue
  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  MAX_CONCURRENCY_LEVEL = 4        -- low on purpose so the load test queues on XSMALL
  STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 600
  COMMENT = 'C02/C09: warehouse elástico para la prueba de carga.';
ALTER WAREHOUSE WH_CARGA_ELASTICA SET TAG
  SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.COST_CENTER = 'CC-100-PLATAFORMA',
  SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.AMBIENTE    = 'SANDBOX',
  SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.PROYECTO    = 'DEMO_SB_PLATAFORMA';   -- tags from session-5/01

CREATE RESOURCE MONITOR IF NOT EXISTS RM_CARGA_ELASTICA
  WITH CREDIT_QUOTA = 10 FREQUENCY = DAILY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 50 PERCENT DO NOTIFY
           ON 90 PERCENT DO SUSPEND
           ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE WH_CARGA_ELASTICA SET RESOURCE_MONITOR = RM_CARGA_ELASTICA;

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE WH_CARGA_ELASTICA TO ROLE FR_DATA_ENGINEER;

-- -----------------------------------------------------------------------------
-- 2. Phase ANTES (single cluster): run from your PC
--    python load_test.py --warehouse WH_CARGA_ELASTICA --sessions 16 --rounds 3 --tag carga-antes
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- 3. Phase DESPUES: enable scale-out (no other change), rerun the same load
--    python load_test.py --warehouse WH_CARGA_ELASTICA --sessions 16 --rounds 3 --tag carga-despues
-- -----------------------------------------------------------------------------
-- Run ONLY after the "antes" load finished (kept commented so "Run All" never skips phase 2):
-- ALTER WAREHOUSE WH_CARGA_ELASTICA SET MAX_CLUSTER_COUNT = 4;   -- elasticity ON
-- (to repeat the demo: ALTER WAREHOUSE WH_CARGA_ELASTICA SET MAX_CLUSTER_COUNT = 1;)
-- The load user needs FR_DATA_ENGINEER granted (e.g. TRIADE / DEVELOPER).
-- Section 6a takes ~1-3 min on XSMALL with 50M rows: that slowness is the point.

-- -----------------------------------------------------------------------------
-- 4. Evidence (C02-AE-03): response time and queueing before vs after,
--    clusters used — the platform scaled by itself
-- -----------------------------------------------------------------------------
SELECT QUERY_TAG                                         AS FASE,
       COUNT(*)                                          AS QUERIES,
       ROUND(AVG(TOTAL_ELAPSED_TIME) / 1000, 2)          AS SEG_PROMEDIO,
       ROUND(APPROX_PERCENTILE(TOTAL_ELAPSED_TIME, 0.95) / 1000, 2) AS SEG_P95,
       ROUND(AVG(QUEUED_OVERLOAD_TIME) / 1000, 2)        AS SEG_EN_COLA_PROMEDIO,
       MAX(CLUSTER_NUMBER)                               AS CLUSTERS_USADOS,
       MIN(START_TIME)                                   AS INICIO,
       MAX(END_TIME)                                     AS FIN
FROM TABLE(SUPERINTENDENCY_DEMO_DB.INFORMATION_SCHEMA.QUERY_HISTORY_BY_WAREHOUSE(
       WAREHOUSE_NAME => 'WH_CARGA_ELASTICA',
       END_TIME_RANGE_START => DATEADD('hour', -3, CURRENT_TIMESTAMP()),
       RESULT_LIMIT => 10000))
WHERE QUERY_TAG IN ('carga-antes', 'carga-despues') AND EXECUTION_STATUS = 'SUCCESS'
GROUP BY 1 ORDER BY INICIO;
-- Threshold for the demo: P95 "despues" <= 50 % of "antes" and queue time ~0.

-- Cluster activity timeline (scale-out and scale-in without intervention)
SELECT TIMESTAMP, EVENT_NAME, EVENT_REASON, EVENT_STATE, CLUSTER_NUMBER
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_EVENTS_HISTORY       -- lags up to ~3 h
WHERE WAREHOUSE_NAME = 'WH_CARGA_ELASTICA'
  AND TIMESTAMP >= DATEADD('day', -1, CURRENT_TIMESTAMP())
ORDER BY TIMESTAMP;

-- -----------------------------------------------------------------------------
-- 5. Peak cost estimate (C09-AE-02): base vs peak, and the control mechanism
-- -----------------------------------------------------------------------------
-- XSMALL = 1 credit/hour per running cluster. Peak cost = base x clusters x duration.
SELECT 'BASE (1 cluster, 1 hora)'  AS ESCENARIO, 1 * 1.0 AS CREDITOS
UNION ALL SELECT 'PICO (4 clusters, 1 hora)', 4 * 1.0
UNION ALL SELECT 'PICO controlado (RM suspende en 9 créditos/día)', 9;
-- Real credits consumed by the test (ACCOUNT_USAGE lags up to ~3 h):
SELECT DATE_TRUNC('hour', START_TIME) AS HORA, ROUND(SUM(CREDITS_USED), 4) AS CREDITOS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE WAREHOUSE_NAME = 'WH_CARGA_ELASTICA' AND START_TIME >= DATEADD('day', -1, CURRENT_TIMESTAMP())
GROUP BY 1 ORDER BY 1;
SHOW RESOURCE MONITORS LIKE 'RM_CARGA_ELASTICA';   -- used_credits / remaining_credits

-- -----------------------------------------------------------------------------
-- 6. Bottleneck (C09-AE-04): provoke, diagnose, fix, verify
-- -----------------------------------------------------------------------------
USE ROLE FR_DATA_ENGINEER;
USE WAREHOUSE WH_CARGA_ELASTICA;          -- XSMALL: too small for this query on 50M rows
ALTER SESSION SET USE_CACHED_RESULT = FALSE;
ALTER SESSION SET QUERY_TAG = 'gargalo-antes';

-- 6a. Provoke: global sort + window over 50M rows -> memory pressure -> spilling
SELECT ID_TARJETA, FECHA_TRANSACCION, MONTO,
       SUM(MONTO) OVER (PARTITION BY ID_TARJETA ORDER BY FECHA_TRANSACCION
                        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ACUMULADO
FROM SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.CREDIT_CARD_TRANSACTIONS
ORDER BY ACUMULADO DESC
LIMIT 100;
SET Q_ANTES = LAST_QUERY_ID();

-- 6b. Diagnose with platform observability: spill + operator breakdown
--     (also: Snowsight > Monitoring > Query History > this query > Query Profile)
SELECT QUERY_ID, WAREHOUSE_SIZE, ROUND(TOTAL_ELAPSED_TIME / 1000, 1) AS SEG,
       BYTES_SPILLED_TO_LOCAL_STORAGE, BYTES_SPILLED_TO_REMOTE_STORAGE,
       PARTITIONS_SCANNED, PARTITIONS_TOTAL
FROM TABLE(SUPERINTENDENCY_DEMO_DB.INFORMATION_SCHEMA.QUERY_HISTORY_BY_SESSION(RESULT_LIMIT => 20))
WHERE QUERY_ID = $Q_ANTES;
SELECT OPERATOR_ID, OPERATOR_TYPE,
       OPERATOR_STATISTICS:spilling:bytes_spilled_local_storage::NUMBER AS SPILL_LOCAL,
       EXECUTION_TIME_BREAKDOWN:overall_percentage::FLOAT              AS PCT_TIEMPO
FROM TABLE(GET_QUERY_OPERATOR_STATS($Q_ANTES))
ORDER BY PCT_TIEMPO DESC NULLS LAST
LIMIT 5;
-- Root cause: the WindowFunction/Sort operator spills to local storage on XSMALL.

-- 6c. Fix: right-size compute for this workload (one command, no data change)
--     and remove the unnecessary global sort; Top-N per card is what the business needs
USE WAREHOUSE WH_TRANSFORM_LARGE;
ALTER SESSION SET QUERY_TAG = 'gargalo-despues';
SELECT ID_TARJETA, MAX(ACUMULADO) AS ACUMULADO
FROM (SELECT ID_TARJETA,
             SUM(MONTO) OVER (PARTITION BY ID_TARJETA ORDER BY FECHA_TRANSACCION
                              ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ACUMULADO
      FROM SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.CREDIT_CARD_TRANSACTIONS)
GROUP BY ID_TARJETA
ORDER BY ACUMULADO DESC
LIMIT 100;
SET Q_DESPUES = LAST_QUERY_ID();

-- 6d. Verify: elapsed time and spill before vs after
SELECT QUERY_TAG, WAREHOUSE_NAME, WAREHOUSE_SIZE, ROUND(TOTAL_ELAPSED_TIME / 1000, 1) AS SEG,
       BYTES_SPILLED_TO_LOCAL_STORAGE AS SPILL_LOCAL, BYTES_SPILLED_TO_REMOTE_STORAGE AS SPILL_REMOTO
FROM TABLE(SUPERINTENDENCY_DEMO_DB.INFORMATION_SCHEMA.QUERY_HISTORY_BY_SESSION(RESULT_LIMIT => 50))
WHERE QUERY_ID IN ($Q_ANTES, $Q_DESPUES)
ORDER BY START_TIME;
ALTER SESSION UNSET QUERY_TAG;
