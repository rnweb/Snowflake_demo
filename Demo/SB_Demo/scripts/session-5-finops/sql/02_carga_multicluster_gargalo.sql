-- Dedicated warehouse so the platform warehouses (Terraform) are untouched.
-- Load is generated by ../python/load_test.py (N concurrent sessions).
-- Idempotent. Run as ACCOUNTADMIN (resource monitor) then FR_DATA_ENGINEER.
