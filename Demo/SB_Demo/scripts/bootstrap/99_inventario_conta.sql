-- =============================================================================
-- 99 — Inventário da conta (para comparar conta antiga x conta nova)
-- =============================================================================
-- Como usar: abra uma worksheet como ACCOUNTADMIN, cole o arquivo inteiro e
-- use "Run All" (Ctrl+Shift+Enter). O último resultado é o inventário completo:
-- baixe em CSV (botão de download da grade) e salve como
--   G:\Superintendency of Banks\Claude - Entregas\Inventario\inventario_<conta>.csv
-- Só leitura sobre a conta: cria apenas o banco vazio ZZ_INVENTARIO e uma
-- tabela TEMPORARY dentro dele (apague o banco ao final).
-- ACCOUNT_USAGE pode atrasar até ~2 h para objetos muito recentes.
-- =============================================================================
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_APP_MEDIUM;   -- se não existir na conta, troque por COMPUTE_WH

-- A tabela temporária precisa de um banco na sessão: usa um banco próprio e
-- vazio, para não depender do que existe na conta. Apagar depois:
--   DROP DATABASE IF EXISTS ZZ_INVENTARIO;
CREATE DATABASE IF NOT EXISTS ZZ_INVENTARIO COMMENT = 'Temporario: inventario da conta (99_inventario_conta.sql)';
USE SCHEMA ZZ_INVENTARIO.PUBLIC;

CREATE OR REPLACE TEMPORARY TABLE INV (CATEGORIA STRING, OBJETO STRING, DETALHE STRING);

-- ---------- objetos via SHOW (sem atraso) ----------
SHOW WAREHOUSES;
INSERT INTO INV SELECT 'WAREHOUSE', "name", "size" || ' | auto_suspend=' || "auto_suspend" || ' | max_cluster=' || "max_cluster_count" || ' | ' || "state" FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW INTEGRATIONS;
INSERT INTO INV SELECT 'INTEGRATION', "name", "type" || ' | enabled=' || "enabled" FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW TASKS IN ACCOUNT;
INSERT INTO INV SELECT 'TASK', "database_name" || '.' || "schema_name" || '.' || "name", "state" || ' | ' || COALESCE("schedule", 'AFTER ' || "predecessors"::STRING) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW STREAMS IN ACCOUNT;
INSERT INTO INV SELECT 'STREAM', "database_name" || '.' || "schema_name" || '.' || "name", "table_name" || ' | stale=' || "stale" FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW STREAMLITS IN ACCOUNT;
INSERT INTO INV SELECT 'STREAMLIT', "database_name" || '.' || "schema_name" || '.' || "name", COALESCE("title", '') FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW NETWORK RULES IN ACCOUNT;
INSERT INTO INV SELECT 'NETWORK_RULE', "database_name" || '.' || "schema_name" || '.' || "name", "type" || ' | ' || "mode" FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW AUTHENTICATION POLICIES IN ACCOUNT;
INSERT INTO INV SELECT 'AUTH_POLICY', "database_name" || '.' || "schema_name" || '.' || "name", '' FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SHOW RESOURCE MONITORS;
INSERT INTO INV SELECT 'RESOURCE_MONITOR', "name", 'quota=' || "credit_quota" || ' | ' || "frequency" FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

-- ---------- objetos via ACCOUNT_USAGE ----------
INSERT INTO INV
SELECT 'DATABASE', DATABASE_NAME, COALESCE(DATABASE_OWNER, '') FROM SNOWFLAKE.ACCOUNT_USAGE.DATABASES
WHERE DELETED IS NULL AND DATABASE_NAME NOT IN ('SNOWFLAKE', 'SNOWFLAKE_SAMPLE_DATA')
UNION ALL
SELECT 'SCHEMA', CATALOG_NAME || '.' || SCHEMA_NAME, COALESCE(SCHEMA_OWNER, '') FROM SNOWFLAKE.ACCOUNT_USAGE.SCHEMATA
WHERE DELETED IS NULL AND CATALOG_NAME NOT IN ('SNOWFLAKE', 'SNOWFLAKE_SAMPLE_DATA') AND SCHEMA_NAME <> 'INFORMATION_SCHEMA'
UNION ALL
SELECT 'TABLE', TABLE_CATALOG || '.' || TABLE_SCHEMA || '.' || TABLE_NAME,
       TABLE_TYPE || ' | rows=' || COALESCE(ROW_COUNT, 0)
FROM SNOWFLAKE.ACCOUNT_USAGE.TABLES
WHERE DELETED IS NULL AND TABLE_TYPE <> 'VIEW' AND TABLE_CATALOG NOT IN ('SNOWFLAKE', 'SNOWFLAKE_SAMPLE_DATA')
UNION ALL
SELECT 'VIEW', TABLE_CATALOG || '.' || TABLE_SCHEMA || '.' || TABLE_NAME, COALESCE(TABLE_OWNER, '') FROM SNOWFLAKE.ACCOUNT_USAGE.VIEWS
WHERE DELETED IS NULL AND TABLE_CATALOG NOT IN ('SNOWFLAKE', 'SNOWFLAKE_SAMPLE_DATA') AND TABLE_SCHEMA <> 'INFORMATION_SCHEMA'
UNION ALL
SELECT 'PROCEDURE', PROCEDURE_CATALOG || '.' || PROCEDURE_SCHEMA || '.' || PROCEDURE_NAME, PROCEDURE_LANGUAGE FROM SNOWFLAKE.ACCOUNT_USAGE.PROCEDURES
WHERE DELETED IS NULL
UNION ALL
SELECT 'FUNCTION', FUNCTION_CATALOG || '.' || FUNCTION_SCHEMA || '.' || FUNCTION_NAME, FUNCTION_LANGUAGE FROM SNOWFLAKE.ACCOUNT_USAGE.FUNCTIONS
WHERE DELETED IS NULL
UNION ALL
SELECT 'STAGE', STAGE_CATALOG || '.' || STAGE_SCHEMA || '.' || STAGE_NAME, STAGE_TYPE FROM SNOWFLAKE.ACCOUNT_USAGE.STAGES
WHERE DELETED IS NULL
UNION ALL
SELECT 'MASKING_POLICY', POLICY_CATALOG || '.' || POLICY_SCHEMA || '.' || POLICY_NAME, POLICY_SIGNATURE FROM SNOWFLAKE.ACCOUNT_USAGE.MASKING_POLICIES
WHERE DELETED IS NULL
UNION ALL
SELECT 'ROW_ACCESS_POLICY', POLICY_CATALOG || '.' || POLICY_SCHEMA || '.' || POLICY_NAME, POLICY_SIGNATURE FROM SNOWFLAKE.ACCOUNT_USAGE.ROW_ACCESS_POLICIES
WHERE DELETED IS NULL
UNION ALL
SELECT 'POLICY_APPLIED', POLICY_NAME || ' -> ' || REF_DATABASE_NAME || '.' || REF_SCHEMA_NAME || '.' || REF_ENTITY_NAME || COALESCE('.' || REF_COLUMN_NAME, ''), POLICY_KIND
FROM SNOWFLAKE.ACCOUNT_USAGE.POLICY_REFERENCES
UNION ALL
SELECT 'TAG', TAG_DATABASE || '.' || TAG_SCHEMA || '.' || TAG_NAME, COALESCE(ARRAY_TO_STRING(ALLOWED_VALUES, ','), '') FROM SNOWFLAKE.ACCOUNT_USAGE.TAGS
WHERE DELETED IS NULL
UNION ALL
SELECT 'ROLE', NAME, COALESCE(COMMENT, '') FROM SNOWFLAKE.ACCOUNT_USAGE.ROLES
WHERE DELETED_ON IS NULL
UNION ALL
SELECT 'USER', NAME, COALESCE(TYPE, 'PERSON') || ' | disabled=' || DISABLED || ' | default_role=' || COALESCE(DEFAULT_ROLE, '') || ' | has_rsa=' || HAS_RSA_PUBLIC_KEY
FROM SNOWFLAKE.ACCOUNT_USAGE.USERS WHERE DELETED_ON IS NULL
UNION ALL
SELECT 'GRANTS_PER_ROLE', GRANTEE_NAME, COUNT(*)::STRING FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_ROLES
WHERE DELETED_ON IS NULL GROUP BY GRANTEE_NAME
UNION ALL
SELECT 'ROLE_HIERARCHY', NAME || ' -> ' || GRANTEE_NAME, '' FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_ROLES
WHERE DELETED_ON IS NULL AND GRANTED_ON = 'ROLE' AND PRIVILEGE = 'USAGE';

-- Contagens reais das tabelas principais (sem atraso).
-- Se a conta ainda não tiver o SUPERINTENDENCY_DEMO_DB carregado e estas duas
-- linhas derem erro, rode só o SELECT final.
INSERT INTO INV
SELECT 'ROWS_LIVE', 'CORE_BANKING_SCHEMA.CREDIT_CARD_TRANSACTIONS', COUNT(*)::STRING FROM SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.CREDIT_CARD_TRANSACTIONS;
INSERT INTO INV
SELECT 'ROWS_LIVE', 'GOVERNANCE_SCHEMA.ROLE_MAPPING', LISTAGG(ROLE_NAME || ':' || BUSINESS_UNIT, ', ') WITHIN GROUP (ORDER BY ROLE_NAME) FROM SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.ROLE_MAPPING;

INSERT INTO INV SELECT 'ACCOUNT', CURRENT_ORGANIZATION_NAME() || '-' || CURRENT_ACCOUNT_NAME(), CURRENT_REGION() || ' | locator=' || CURRENT_ACCOUNT();

-- ===== RESULTADO: baixe este em CSV =====
SELECT * FROM INV ORDER BY CATEGORIA, OBJETO;
