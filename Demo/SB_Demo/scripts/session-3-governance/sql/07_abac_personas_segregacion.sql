CREATE ROLE IF NOT EXISTS FR_DEV_ENGINEER
  COMMENT = 'Ingeniería en DEV: acceso total al clon SUPERINTENDENCY_DEMO_DB_DEV, ninguno a PROD.';
GRANT ROLE FR_DEV_ENGINEER TO ROLE FR_DEMO_ADMIN;
GRANT USAGE ON WAREHOUSE WH_INGESTION_MEDIUM TO ROLE FR_DEV_ENGINEER;
GRANT USAGE ON DATABASE SUPERINTENDENCY_DEMO_DB_DEV TO ROLE FR_DEV_ENGINEER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE SUPERINTENDENCY_DEMO_DB_DEV TO ROLE FR_DEV_ENGINEER;
GRANT SELECT ON ALL TABLES IN DATABASE SUPERINTENDENCY_DEMO_DB_DEV TO ROLE FR_DEV_ENGINEER;
GRANT SELECT ON ALL VIEWS  IN DATABASE SUPERINTENDENCY_DEMO_DB_DEV TO ROLE FR_DEV_ENGINEER;
GRANT SELECT ON FUTURE TABLES IN DATABASE SUPERINTENDENCY_DEMO_DB_DEV TO ROLE FR_DEV_ENGINEER;
-- No grant at all on SUPERINTENDENCY_DEMO_DB (PROD).

-- The DEV clone carries its own ROLE_MAPPING table, but its RLS policy was cloned
-- from PROD and reads SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.ROLE_MAPPING by
-- full name. Without the step below, the DEV role sees 0 rows (the DEV mapping
-- rows are ignored). Fix (verified 2026-10-29): a DEV-bound copy of the policy,
-- attached to the DEV table only. PROD is not touched.
INSERT INTO SUPERINTENDENCY_DEMO_DB_DEV.GOVERNANCE_SCHEMA.ROLE_MAPPING (ROLE_NAME, BUSINESS_UNIT, DESCRIPTION)
SELECT 'FR_DEV_ENGINEER', u.U, 'Ingeniería DEV (C07-AE-04)'
FROM (SELECT * FROM VALUES ('PYME'), ('CORPORATIVO'), ('RETAIL') AS v(U)) u
WHERE NOT EXISTS (SELECT 1 FROM SUPERINTENDENCY_DEMO_DB_DEV.GOVERNANCE_SCHEMA.ROLE_MAPPING m
                  WHERE m.ROLE_NAME = 'FR_DEV_ENGINEER' AND m.BUSINESS_UNIT = u.U);

CREATE OR REPLACE ROW ACCESS POLICY SUPERINTENDENCY_DEMO_DB_DEV.GOVERNANCE_SCHEMA.RLS_BUSINESS_UNIT_DEV
  AS (business_unit VARCHAR) RETURNS BOOLEAN ->
    CASE
      WHEN current_role() IN ('FR_DEMO_ADMIN', 'ACCOUNTADMIN') THEN TRUE
      ELSE EXISTS (
        SELECT 1 FROM SUPERINTENDENCY_DEMO_DB_DEV.GOVERNANCE_SCHEMA.ROLE_MAPPING m
        WHERE m.ROLE_NAME = current_role() AND m.BUSINESS_UNIT = business_unit)
    END
  COMMENT = 'DEV copy of RLS_BUSINESS_UNIT, bound to the DEV ROLE_MAPPING (C07-AE-04).';
ALTER TABLE SUPERINTENDENCY_DEMO_DB_DEV.CORE_BANKING_SCHEMA.CREDIT_CARD_TRANSACTIONS
  DROP ROW ACCESS POLICY SUPERINTENDENCY_DEMO_DB_DEV.GOVERNANCE_SCHEMA.RLS_BUSINESS_UNIT;
ALTER TABLE SUPERINTENDENCY_DEMO_DB_DEV.CORE_BANKING_SCHEMA.CREDIT_CARD_TRANSACTIONS
  ADD ROW ACCESS POLICY SUPERINTENDENCY_DEMO_DB_DEV.GOVERNANCE_SCHEMA.RLS_BUSINESS_UNIT_DEV ON (UNIDAD_NEGOCIO);

