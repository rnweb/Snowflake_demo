-- -----------------------------------------------------------------------------
-- 3. ABAC (C07-PRE-02 / C07-AE-02): user attributes + attribute-based RLS
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.USER_ATTRIBUTES (
    USER_NAME  VARCHAR NOT NULL,
    ATRIBUTO   VARCHAR NOT NULL,
    VALOR      VARCHAR NOT NULL,
    COMENTARIO VARCHAR
) COMMENT = 'C07 ABAC: atributos por usuario (no por rol).';
CREATE TABLE IF NOT EXISTS SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.CIUDAD_REGION (
    CIUDAD VARCHAR NOT NULL,
    REGION VARCHAR NOT NULL
) COMMENT = 'C07 ABAC: ciudad -> macro-región (atributo de los datos).';

MERGE INTO SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.CIUDAD_REGION t
USING (SELECT * FROM VALUES
         ('Antofagasta', 'NORTE'), ('La Serena', 'NORTE'),
         ('Valparaiso', 'CENTRO'), ('Vina del Mar', 'CENTRO'), ('Santiago', 'CENTRO'), ('Rancagua', 'CENTRO'),
         ('Chillan', 'SUR'), ('Concepcion', 'SUR'), ('Temuco', 'SUR'), ('Puerto Montt', 'SUR')
       AS v(CIUDAD, REGION)) s
ON t.CIUDAD = s.CIUDAD
WHEN MATCHED THEN UPDATE SET REGION = s.REGION
WHEN NOT MATCHED THEN INSERT (CIUDAD, REGION) VALUES (s.CIUDAD, s.REGION);

MERGE INTO SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.USER_ATTRIBUTES t
USING (SELECT 'ANALISTA_NORTE' AS USER_NAME, 'REGION' AS ATRIBUTO, 'NORTE' AS VALOR,
              'Analista zonal Norte' AS COMENTARIO) s
ON t.USER_NAME = s.USER_NAME AND t.ATRIBUTO = s.ATRIBUTO
WHEN MATCHED THEN UPDATE SET VALOR = s.VALOR
WHEN NOT MATCHED THEN INSERT VALUES (s.USER_NAME, s.ATRIBUTO, s.VALOR, s.COMENTARIO);
-- ANALISTA_SIN_REGION intentionally has NO row: right role, missing attribute.

CREATE ROW ACCESS POLICY IF NOT EXISTS SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.RLS_REGION_ATRIBUTO
  AS (P_CIUDAD VARCHAR) RETURNS BOOLEAN ->
    CURRENT_ROLE() IN ('FR_DEMO_ADMIN', 'ACCOUNTADMIN')
    OR EXISTS (
        SELECT 1
        FROM SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.USER_ATTRIBUTES ua
        JOIN SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.CIUDAD_REGION cr
          ON cr.REGION = ua.VALOR
        WHERE ua.USER_NAME = CURRENT_USER()
          AND ua.ATRIBUTO = 'REGION'
          AND cr.CIUDAD = P_CIUDAD)   -- distinct arg name: avoids self-comparison
  COMMENT = 'C07 ABAC: el usuario sólo ve ciudades de su atributo REGION.';

-- Governed regional view: RBAC policy (unit, by role) on the table + ABAC policy (region, by user) on the view
CREATE OR REPLACE SECURE VIEW SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.VW_TRANSACCIONES_REGIONAL
  COMMENT = 'C07: RBAC (unidad por rol) + ABAC (región por atributo del usuario).'
AS SELECT ID_TRANSACCION, RUT, NUMERO_TARJETA, FECHA_TRANSACCION, MONTO, CATEGORIA, CIUDAD, ESTADO, UNIDAD_NEGOCIO
   FROM SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.CREDIT_CARD_TRANSACTIONS;
ALTER VIEW SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.VW_TRANSACCIONES_REGIONAL
  ADD ROW ACCESS POLICY SUPERINTENDENCY_DEMO_DB.GOVERNANCE_SCHEMA.RLS_REGION_ATRIBUTO ON (CIUDAD);
GRANT SELECT ON VIEW SUPERINTENDENCY_DEMO_DB.CORE_BANKING_SCHEMA.VW_TRANSACCIONES_REGIONAL TO ROLE FR_BI_ANALYST;

